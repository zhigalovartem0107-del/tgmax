_WORD = re.compile(r"[A-Za-zА-Яа-яЁёІіЇїЄєҐґ][A-Za-zА-Яа-яЁёІіЇїЄєҐґ0-9]*(?:[-'’][A-Za-zА-Яа-яЁёІіЇїЄєҐґ0-9]+)*")
_CYR = re.compile(r"[А-Яа-яЁёІіЇїЄєҐґ]")
_LINK_MD = re.compile(r"\[([^\]]*)\]\([^)]*\)")
_URL = re.compile(r"(?:https?://|www\.)\S+|\b[\w-]+\.(?:ru|com|me|org|net|io|рф)(?:/\S*)?", re.I)
_MENTION = re.compile(r"(?<![\w@])@\w+")


def clean(text):
    """Текст без оформления: 𝐑𝐨𝐛𝐥𝐨𝐱 -> Roblox, [текст](ссылка) -> текст, без ссылок и @упоминаний."""
    t = unicodedata.normalize("NFKC", str(text or ""))
    t = _LINK_MD.sub(r"\1", t)
    t = _URL.sub(" ", t)
    t = _MENTION.sub(" ", t)
    return t.replace("**", "").replace("__", "").replace("~~", "").replace("`", "")


def norm(word):
    return str(word or "").lower().replace("ё", "е")


def is_cyr(word):
    return bool(_CYR.search(word or ""))


def words(text):
    """Слова текста как есть (без ссылок и оформления)."""
    return _WORD.findall(clean(text))


def stem(word):
    """Грубая основа: «обновлением» -> «обновл», «игроков» -> «игрок», «Roblox» -> «roblox», «stars» -> «star»."""
    w = norm(word).strip("-'’")
    if is_cyr(w):
        for end in _ENDINGS:
            if w.endswith(end) and len(w) - len(end) >= 3:
                w = w[:-len(end)]
                break
        return w[:6]
    if w.endswith("'s") or w.endswith("’s"):
        w = w[:-2]
    elif len(w) > 4 and w.endswith("s") and not w.endswith("ss"):
        w = w[:-1]
    return w[:8]


def content_words(text):
    """Значимые слова: без служебных, мусорных (подпишись, канал…) и коротких."""
    out = []
    for w in words(text):
        n = norm(w)
        if len(n) >= 3 and n not in STOP and n not in NOISE and not n.isdigit():
            out.append(w)
    return out


def stems(text):
    return {stem(w) for w in content_words(text)}


def near_duplicate(a, b):
    """Две новости про одно и то же: у заголовков ≥3 общих основы и они — ≥60% меньшего из заголовков
    (короткие заголовки — совпадают целиком). a, b — множества основ (stems())."""
    a, b = set(a or ()), set(b or ())
    shared, small = len(a & b), min(len(a), len(b))
    if not small:
        return False
    if small <= 2:
        return shared == small
    return shared >= 3 and shared / small >= 0.6


def cyr_share(texts):
    """Доля кириллицы среди букв: по ней выбираем, искать русские новости или английские."""
    letters = cyr = 0
    for t in texts:
        for ch in str(t or ""):
            if ch.isalpha():
                letters += 1
                cyr += bool(_CYR.match(ch))
    return cyr / letters if letters else 1.0
