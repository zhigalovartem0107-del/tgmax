class CodedError(RuntimeError):
    """Исключение со своим кодом: CodedError("ERR_YK_401", "ЮKassa 401: …"). Пойманное — пишется с этим кодом."""

    def __init__(self, code, details=""):
        super().__init__(details or get(code).text)
        self.code = code


def get(code):
    """Описание кода; неизвестный код (опечатка, старая версия) — внутренняя ошибка, а не падение бота."""
    return ERRORS.get(code) or ERRORS["ERR_INTERNAL"]


def tag(code):
    return f"[{get(code).code}]"


def line(code, details=""):
    """Строка журнала: «[ERR_AI_429] Лимиты ИИ исчерпаны (все ключи вернули 429) — подробности»."""
    info = get(code)
    return f"[{info.code}] {info.text}" + (f" — {details}" if details else "")


def user(code, text=""):
    """Покупателю: вежливый текст и в конце код — его можно прислать в поддержку. Без технических подробностей."""
    text = (text or "😔 Что-то пошло не так — попробуй ещё раз чуть позже. Если повторится, пришли этот код в "
                    "поддержку.").rstrip()
    return f"{text}\n\nКод ошибки: {get(code).code}"


def admin(code, details="", what=""):
    """Хозяину и админам: код, описание, что случилось, точные технические подробности и что сделать."""
    info = get(code)
    out = [f"{LEVELS[info.level][0]} [{info.code}] {info.text}"]
    if what:
        out.append(str(what).strip())
    if details:
        out.append(f"Подробности: {str(details).strip()}")
    out.append(f"Что сделать: {info.fix}")
    return "\n".join(out)


def codes_in(text):
    """Коды ошибок в тексте (по порядку)."""
    return CODE_RE.findall(str(text or ""))


def ai_code(kinds):
    """Код отказа ИИ по причинам с каждого ключа: «429», «timeout», «key» (не принят), «error». Все 429 —
    ERR_AI_429; все тайм-ауты — ERR_AI_TIMEOUT; хоть один ключ не принят — ERR_AI_KEY (его надо менять); иначе —
    тайм-аут, лимит или общий сбой; ключей нет вовсе — ERR_AI_NO_KEYS."""
    kinds = list(kinds or ())
    if not kinds:
        return "ERR_AI_NO_KEYS"
    if all(k == "429" for k in kinds):
        return "ERR_AI_429"
    if all(k == "timeout" for k in kinds):
        return "ERR_AI_TIMEOUT"
    for kind, code in (("key", "ERR_AI_KEY"), ("timeout", "ERR_AI_TIMEOUT"), ("429", "ERR_AI_429")):
        if kind in kinds:
            return code
    return "ERR_AI_FAIL"


def yk_code(status):
    """Код по ответу ЮKassa (HTTP-статус); нет ответа (None) — нет связи."""
    if status is None:
        return "ERR_YK_NET"
    return {400: "ERR_YK_400", 401: "ERR_YK_401", 403: "ERR_YK_403"}.get(int(status), "ERR_YK_HTTP")


def _timeout(e):
    return isinstance(e, TimeoutError) or "Timeout" in type(e).__name__ or "timed out" in str(e).lower()


def classify(e, default="ERR_INTERNAL"):
    """Код для пойманного исключения: свой код исключения (строка из реестра) — он; тайм-аут — ERR_TIMEOUT; нет сети —
    ERR_NET; диск полон или только для чтения — ERR_DATA_WRITE; прочее — default."""
    if e is None:
        return default
    code = getattr(e, "code", None)
    if isinstance(code, str) and code in ERRORS:        # у Telethon code — число: это не наш код
        return code
    if _timeout(e):
        return "ERR_TIMEOUT"
    name = type(e).__name__
    if isinstance(e, ConnectionError) or name in ("ConnectionError", "ProxyError", "SSLError") \
            or "ConnectionError" in name:
        return "ERR_NET"
    if isinstance(e, OSError) and e.errno in (errno.ENOSPC, errno.EROFS, errno.EDQUOT):
        return "ERR_DATA_WRITE"
    return default


